# ============================================================
# 文件主题：索引与切片（含布尔掩码取列）
# 核心结论：
#   1. data[2,3]：用「行下标, 列下标」取单个元素（类似 numpy 的写法）
#   2. data[2] 取第 2 行；data[2]>2 把这一行的每个元素与 2 比较，得到布尔数组
#   3. data[:, index]：用布尔数组当「掩码」，只保留对应位置为 True 的列
# 易混点：data[i,j] 的逗号表示「先取行再取列」；
#         布尔索引得到的是「满足条件位置的子集」，形状会变小
#         下标从 0 开始计数，最后一个元素下标是「长度-1」
# ============================================================
import torch
# 单独一个 # 是空注释行，不影响运行
#
torch.random.manual_seed(22)
# torch.randint(0,10,[4,5])：生成 4 行 5 列、元素取值在 [0,10) 的随机整数张量
data =torch.randint(0,10,[4,5])
print(data)

# data[2,3]：取第 2 行、第 3 列交叉处的那个元素（下标从 0 计数）
# 想验证时取消注释即可
# print(data[2,3])

# data[[1, 2], [2, 4]]：高级索引（花式索引），同时给出「行下标列表」和「列下标列表」，
# 一一对应地取 (1,2) 和 (2,4) 两个元素，结果是一维张量
# print(data[[1, 2], [2, 4]])
#
# data[[[1], [3]], [1, 3]]：更复杂的花式索引组合，行下标是二维 [[1],[3]]、
# 列下标是 [1,3]，用于体会「下标数组的形状决定输出形状」这一规则（初学者可先跳过）
# print(data[[[1], [3]], [1, 3]])

# data[:2, 1:4:2]：切片。行取第 0、1 行（:2 不含第 2 行）；
# 列从 1 开始到 4（不含 4），步长为 2，即取第 1、3 列 → 结果 2 行 2 列
# print(data[:2, 1:4:2])

# data[2]：取第 2 行（一维，含 5 个元素）；与 2 逐个比较，
# 得到长度 5 的布尔张量，如 tensor([True, False, ...])，元素为 True 表示该列数值 > 2
index = data[2]>2
print(index)
# data[:, index]：data[:, 布尔掩码] 表示「所有行都保留，但只保留 index 里为 True 的那些列」
# 结果的行数仍是 4，列数变成 index 中 True 的个数
print(data[:,index])


