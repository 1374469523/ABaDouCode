# ============================================================
# 文件主题：标量（scalar）与 .item() 取值
# 核心结论：
#   1. torch.tensor([30,]) 创建的是「只含一个元素」的一维张量
#   2. .item() 能把张量中唯一的那个元素提取成 Python 原生数字（int / float）
# 易混点：.item() 只对「只有一个元素」的张量有效，多元素张量会报错；
#         多元素想转成 Python 对象要用 data.tolist()
# ============================================================
import torch

# torch.tensor([30,])：传列表 [30,] 创建一维张量，只有一个元素 30
# 列表里的逗号可有可无，写成 [30] 也一样
data =torch.tensor([30,])
# 打印张量本身：输出 tensor([30])
print(data)
# data.item()：取出张量里唯一的那个数，得到 Python 原生 int 30（不再是张量对象）
print(data.item())