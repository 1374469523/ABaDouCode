# ============================================================
# 文件主题：线性张量（arange / linspace）与随机张量（randn）
# 核心结论：
#   1. arange 按「步长」生成等差序列；linspace 按「个数」把区间等分
#   2. randn 从标准正态分布采样，每次运行结果都不同
#   3. 用 torch.random.manual_seed(种子) 固定随机种子后，随机数序列可复现
#      （同一机器、同一种子，每次运行结果一样，方便调试与复现实验）
# 易混点：arange 的第三个参数是「步长」，linspace 的第三个参数是「个数」，
#         两者含义不同，别混淆
# ============================================================
import torch

# ===== 线性张量：arange 按「步长」生成，linspace 按「个数」生成 =====
# torch.arange(0, 10, 1)：三个参数分别代表 起始=0、终止=10（不含）、步长=1
# → 生成 [0,1,2,...,9]，共 10 个元素（注意 10 本身不包含在内）
print(torch.arange(0, 10, 1))
# torch.linspace(0, 10, 11)：三个参数分别代表 起始=0、终止=10、个数=11
# → 在 [0,10] 区间内（含首尾）等分成 11 个数，得到 [0,1,2,...,10]
print(torch.linspace(0, 10, 11))

# ===== 随机张量：randn 产生随机数，种子决定随机序列 =====
# torch.randn(2, 3)：从标准正态分布 N(0,1)（均值 0、方差 1）采样，生成 2x3 随机矩阵
# 参数 2 和 3 分别代表行数和列数；每次运行结果不同
print(torch.randn(2, 3))
# torch.random.initial_seed()：查看本次运行当前使用的随机种子（一个整数）
print(torch.random.initial_seed())

# ===== 固定随机种子，让随机结果可复现 =====
# manual_seed(100)：把随机种子固定为 100，之后产生的随机数序列就确定了
torch.random.manual_seed(100)
# 设种子后再 randn，结果固定：每次运行打印的数字都一样，便于对比和调试
print(torch.randn(2, 3))
# 此时当前初始种子已变为 100，与手动设置的值一致
print(torch.random.initial_seed())