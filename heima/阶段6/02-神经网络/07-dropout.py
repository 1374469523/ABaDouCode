# 演示主题：Dropout（随机丢弃神经元）
# 核心结论：
#   1. 过拟合（Overfitting）：模型在训练集上表现很好、但在测试集上表现差，
#      原因是模型“死记硬背”训练数据，没有学到通用规律。
#   2. Dropout 是缓解过拟合最常用的正则化手段之一：训练时每个神经元
#      以概率 p 被随机“丢弃”（输出置 0），相当于每次训练都用一个
#      “瘦身”的随机子网络，多个子网络平均后泛化能力更强，也迫使神经元
#      不过度依赖彼此、各自学到更独立的特征。
#   3. 注意：Dropout 只在训练时生效（model.train() 状态），
#      预测/评估时要关闭（model.eval()），否则随机丢弃会破坏预测结果。
#      此外丢弃后剩余神经元会被放大 1/(1-p) 倍，以保持输出整体数值不变。
#   4. p 是丢弃概率：p=0 表示不丢弃，p=1 表示全部丢弃（无意义）。
#      本例 p=0.75 表示每个神经元有 75% 概率被置 0。
# ============================================================

import torch
import torch.nn as nn

# torch.random.manual_seed(22)
# 上面：固定随机种子，保证每次运行随机丢弃的结果一致（便于复现）。

input = torch.randn([1,4])   # 构造输入：1 个样本、4 个特征
layer = nn.Linear(in_features=4, out_features=5)   # 全连接层：4 维输入 -> 5 维输出
y = layer(input)             # 前向传播，得到 5 个输出值
print(y)                     # 打印丢弃前的输出（所有 5 个神经元都有非零数值）

dropout =nn.Dropout(p=0.75)  # 创建 Dropout 层：p=0.75 表示每个神经元有 75% 概率被随机置 0
out =dropout(y)              # 应用 Dropout：部分神经元被随机丢弃（变成 0）
print(out)                   # 打印丢弃后的输出：会发现约 3/4 的神经元是 0，剩下约 1/4 被保留并放大
